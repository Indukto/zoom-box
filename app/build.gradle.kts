      val hasReleaseKey = !System.getenv("STORE_PASSWORD").isNullOrEmpty()
        && !System.getenv("KEY_PASSWORD").isNullOrEmpty()
        && file(keystorePath).exists()
      if (hasReleaseKey) {
        signingConfig = signingConfigs.getByName("release")
